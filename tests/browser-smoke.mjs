  await page.locator('#generate').click();
  assert.deepEqual((await savedSettings()).materials, randomBefore.materials);
  await page.locator('[data-palette-mode="random"]').click();
  await page.locator('#generate').click();
  const randomAfter = await savedSettings();
  assert.ok(coherent(randomAfter.materials), 'Generate uses the same coordinated palette selection');
  assert.notDeepEqual(randomAfter.materials, randomBefore.materials);
  await page.locator('#undo').click(); assert.deepEqual((await savedSettings()).materials, randomBefore.materials);
  await page.locator('#redo').click(); assert.deepEqual((await savedSettings()).materials, randomAfter.materials);
  await page.locator('#explore').click();
  assert.equal(await page.locator('[data-candidate]').count(), 6);
  await page.screenshot({ path: new URL('design-explorer.png', out).pathname.replace(/^\/([A-Z]:)/, '$1'), fullPage: true, animations: 'disabled' });
  const candidateBefore = await page.locator('[data-candidate="0"] canvas').evaluate(c => c.toDataURL());
  await page.locator('#more-designs').click();
  assert.notEqual(await page.locator('[data-candidate="0"] canvas').evaluate(c => c.toDataURL()), candidateBefore);
  const chosenName = await page.locator('[data-candidate="2"] strong').innerText();
