  const beforeWeirdness = await savedSettings();
  await page.locator('#weirdness').fill('100');
  await page.locator('#weirdness').dispatchEvent('change');
  assert.equal(await page.locator('#weirdness-value').innerText(), '100%');
  assert.equal((await savedSettings()).weirdness, 100);
  assert.deepEqual((await savedSettings()).materials, beforeWeirdness.materials);
  assert.equal((await savedSettings()).seed, beforeWeirdness.seed);
  await page.locator('#undo').click();
  assert.equal(await page.locator('#weirdness').inputValue(), String(beforeWeirdness.weirdness));
  await page.locator('#tab-blocks').click();
  await page.locator('#palette').selectOption('random');
  const beforeRoll = await savedSettings();
  assert.ok(coherent(beforeRoll.materials), 'Random palette dropdown chooses a whole coordinated family');
  await page.locator('#random-palette').click();
  assert.equal((await savedSettings()).seed, beforeRoll.seed);
  assert.notDeepEqual((await savedSettings()).materials, beforeRoll.materials);
  assert.ok(coherent((await savedSettings()).materials), 'Shuffle rolls a coordinated palette');
