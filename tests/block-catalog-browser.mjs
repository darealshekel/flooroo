import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { BLOCKS } from '../src/catalog.js';
import { encodeCell } from '../src/editing.js';

await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  await page.goto('http://127.0.0.1:4406');
  await page.locator('#loading').waitFor({ state: 'hidden' });
  await page.locator('#tab-blocks').click();
  assert.equal(await page.locator('#palette option[value="random"]').innerText(), 'Random palette');
  assert.equal(await page.locator('#random-palette').getAttribute('aria-label'), 'Randomize palette now');
  await page.locator('#version').selectOption('1.12.2');
  await page.locator('#block-library').click();
  await page.locator('#clear-shown').click();
  assert.ok(await page.locator('#apply-blocks').isDisabled());
  await page.locator('#library-group').selectOption('Slabs');
  assert.ok(await page.locator('input[value="oak_slab"]').isVisible());
  assert.equal(await page.locator('input[value="cherry_slab"]').count(), 0);
  await page.locator('input[value="oak_slab"]').check();
  assert.ok(await page.locator('#apply-blocks').isDisabled());
  await page.locator('#library-group').selectOption('Stairs');
  await page.locator('input[value="oak_stairs"]').check();
  assert.equal(await page.locator('#selection-count').innerText(), '2 / 16 selected');
  assert.ok(await page.locator('#apply-blocks').isEnabled());
  await page.locator('#apply-blocks').click();
  const settings = () => page.evaluate(() => JSON.parse(localStorage.getItem('mmm-floor-v3')));
  assert.deepEqual((await settings()).allowedBlocks, ['oak_slab', 'oak_stairs']);
  await page.locator('[data-palette-mode="random"]').click();
  await page.locator('#generate').click();
  assert.ok((await settings()).materials.every(id => ['oak_slab', 'oak_stairs'].includes(id)));
  await page.reload();
  await page.locator('#loading').waitFor({ state: 'hidden' });
  await page.locator('#tab-blocks').click();
  await page.locator('#block-library').click();
  assert.equal(await page.locator('#selection-count').innerText(), '2 / 16 selected');
  await page.locator('#library-group').selectOption('Wool');
  await page.locator('#select-shown').click();
  assert.equal(await page.locator('#selection-count').innerText(), '16 / 16 selected');
  assert.equal(await page.locator('#library-blocks input:checked').count(), 14, 'hidden selections count toward 16');
  const unavailable = page.locator('#library-blocks input:not(:checked)').first();
  assert.ok(await unavailable.isDisabled());
  await page.locator('#library-blocks input:checked').first().uncheck();
  assert.ok(await unavailable.isEnabled());
  await unavailable.focus();
  await page.keyboard.press('Space');
  assert.equal(await page.locator('#selection-count').innerText(), '16 / 16 selected');
  await page.locator('#apply-blocks').click();
  assert.equal((await settings()).allowedBlocks.length, 16);
  const saved = (await settings()).allowedBlocks;
  await page.locator('#block-library').click();
  await page.locator('#clear-shown').click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.deepEqual((await settings()).allowedBlocks, saved, 'cancel preserves pool');

  // Every new shape is visible in both pickers and the renderer, not just listed in data.
  const ids = ['oak_slab', 'stone_brick_stairs', 'quartz_pillar', 'waxed_oxidized_cut_copper_stairs', 'white_glazed_terracotta', 'red_sandstone_slab', 'deepslate_tiles'];
  const cells = Array.from({ length: 32 ** 2 }, (_, i) => encodeCell(BLOCKS.findIndex(b => b.id === ids[Math.floor(i % 32 / 5) % ids.length])));
  const design = { format: 'flooroo', version: 4, settings: { version: '26.3', width: 32, depth: 32, tile: 32, border: 0, editLayer: { size: 32, cells } } };
  await page.locator('#import-file').setInputFiles({ name: 'shapes.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(design)) });
  await page.waitForFunction(() => document.getElementById('version').value === '26.3');
  await page.locator('#swatches button').first().click();
  await page.locator('#block-search').fill('waxed oxidized');
  assert.ok(await page.locator('[data-block="waxed_oxidized_cut_copper_stairs"]').isVisible());
  await page.getByRole('button', { name: 'Close block picker', exact: true }).click();

  const pixels = async () => page.locator('#three-container canvas').evaluate(canvas => {
    const gl = canvas.getContext('webgl2') || canvas.getContext('webgl');
    const data = new Uint8Array(gl.drawingBufferWidth * gl.drawingBufferHeight * 4);
    gl.readPixels(0, 0, gl.drawingBufferWidth, gl.drawingBufferHeight, gl.RGBA, gl.UNSIGNED_BYTE, data);
    return data.filter((value, i) => i % 4 === 3 && value > 0).length;
  });
  await page.locator('#view-3d').click();
  await page.waitForTimeout(500);
  assert.ok(await pixels() > 1000);
  await page.screenshot({ path: 'test-results/block-shapes-desktop.png', animations: 'disabled' });
  const canvas = await page.locator('#three-container canvas').boundingBox();
  await page.mouse.move(canvas.x + canvas.width / 2, canvas.y + canvas.height / 2);
  await page.mouse.down();
  await page.mouse.move(canvas.x + canvas.width / 2 + 90, canvas.y + canvas.height / 2 + 20, { steps: 8 });
  await page.mouse.up();
  assert.ok(await pixels() > 1000);
  await page.locator('#block-library').click();
  await page.locator('#library-group').selectOption('Stairs');
  assert.ok(await page.locator('input[value="poplar_stairs"]').count());
  await page.screenshot({ path: 'test-results/stairs-picker-desktop.png', animations: 'disabled' });
  assert.ok(await page.locator('#library-blocks img').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0)));
  await page.getByRole('button', { name: 'Close block selection', exact: true }).click();

  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  assert.ok(await pixels() > 1000);
  await page.screenshot({ path: 'test-results/block-shapes-mobile.png', animations: 'disabled' });
  await page.locator('#block-library').click();
  await page.locator('#library-group').selectOption('Slabs');
  await page.screenshot({ path: 'test-results/slabs-picker-mobile.png', animations: 'disabled' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator('#library-dialog').evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.locator('#library-group').selectOption('');
  await page.locator('#library-search').fill('waxed oxidized');
  assert.ok(await page.locator('input[value="waxed_oxidized_cut_copper_stairs"]').count());
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', catalog: BLOCKS.length, poolLimits: [2, 16], legacyShapes: true, persistence: true, keyboard: true, desktopMobile3D: true, errors }));
} finally { await browser.close(); }
